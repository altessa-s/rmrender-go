"""Re-vendor the C libraries this module compiles.

    python3 scripts/vendor.py --rmrender ../rmrender-lib --rmlines ../rmlines-lib \\
        --rmdoc ../rmdoc-lib --rmmarks ../rmmarks-lib --pdfium /path/to/pdfium

Copies from each clean checkout the sources and headers this module builds,
with their licences and notices, into internal/clib/<library>/, and records
the commit of each in internal/clib/VERSION. rmrender-lib's page templates
land in internal/clib/rmrender/resources/templates (embedded by the main
package) and its fonts in fonts/ (embedded by package fonts). miniz is copied
byte for byte into internal/clib/rmdoc/miniz rather than a vendor directory,
because the Go module zip leaves out files below a directory named vendor;
the two rmdoc-lib lines that include ../vendor/miniz/ are pointed at
../miniz/ and nothing else changes.

It then writes, in the package directory:

* one clib_<library>_<name>.c per vendored C source, which compiles it into
  the package (cgo builds only the C files of the package directory), with
  the build constraint of its backend;
* clib_digest.h, a digest of internal/clib, which every wrapper includes so
  that a change down there rebuilds the package;
* clib_symbols.h, which renames every external symbol of the vendored code
  with the rmrgo_ prefix. clib_prelude.h includes it, and cgo force-includes
  the prelude into every C file of the package, so this module links beside
  rmlines-go, rmdoc-go and rmmarks-go, which compile the same libraries under
  their own names. internal/coexist proves it, and a test of the package
  fails on any symbol left unprefixed.

The symbols are read with nm from objects compiled here, for both backends:
the Apple one needs macOS, the Cairo one pkg-config with Cairo, Pango,
Fontconfig, HarfBuzz and GdkPixbuf (Homebrew provides them on macOS) and the
PDFium headers given by --pdfium (rmrender-lib's scripts/fetch-pdfium.py
fetches them). Everything is assembled and checked in a staging directory and
swapped in whole: on any failure the previous tree stays as it was.

Windows builds the Cairo backend from the same sources, and the macOS objects
stand for it: the _WIN32 branches of the vendored code define only static
functions, or the same external names as the POSIX branches (rmd_fopen,
rmd_seek, rmd_unmap, rmr_locale_*), so the list read here is the Windows
list too. TestVendoredSymbolsArePrefixed reads the PE symbol table of the
Windows test binary and fails if a later version breaks that.
"""

import argparse
import concurrent.futures
import hashlib
import os
import platform
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HEADER = """\
// Copyright 2026 ALTESSA SOLUTIONS INC.
// Use of this source code is governed by an MIT-style license that can be
// found in the LICENSE file.
"""

GENERATED = "Generated by scripts/vendor.py; do not edit."

# The backend each system builds: CoreGraphics on darwin, unless the
# rmrender_cairo build tag asks for Cairo; Cairo, Pango and PDFium on linux
# and windows. cgo.go and unsupported.go say the same.
APPLE = "darwin && !rmrender_cairo"
CAIRO = "linux || windows || (darwin && rmrender_cairo)"

CAIRO_PACKAGES = ["cairo", "pangocairo", "pangoft2", "fontconfig", "harfbuzz", "gdk-pixbuf-2.0"]

# What each library contributes: directories copied whole (regular files
# only), single files copied to a new name, and the source directories whose
# C files are compiled.
LIBRARIES = {
    "rmrender": {
        "repository": "rmrender-lib",
        "directories": {
            "src": "src",
            "adapters": "adapters",
            "backends/common": "backends/common",
            "backends/apple": "backends/apple",
            "backends/linux": "backends/linux",
            "include/rmrender": "include/rmrender",
            "resources/templates": "resources/templates",
        },
        "files": {
            "LICENSE": "LICENSE",
            "COPYRIGHT": "COPYRIGHT",
            "resources/UNICODE-LICENSE.txt": "UNICODE-LICENSE.txt",
            "scripts/fetch-pdfium.py": "scripts/fetch-pdfium.py",
        },
    },
    "rmlines": {
        "repository": "rmlines-lib",
        "directories": {"src": "src", "include/rmlines": "include/rmlines"},
        "files": {"LICENSE": "LICENSE", "COPYRIGHT": "COPYRIGHT"},
    },
    "rmdoc": {
        "repository": "rmdoc-lib",
        "directories": {"src": "src", "include/rmdoc": "include/rmdoc", "vendor/miniz": "miniz"},
        "files": {
            "LICENSE": "LICENSE",
            "COPYRIGHT": "COPYRIGHT",
            "THIRD-PARTY.md": "THIRD-PARTY.md",
            "UNICODE-LICENSE.txt": "UNICODE-LICENSE.txt",
        },
    },
    "rmmarks": {
        "repository": "rmmarks-lib",
        "directories": {"src": "src", "include/rmmarks": "include/rmmarks"},
        "files": {
            "LICENSE": "LICENSE",
            "COPYRIGHT": "COPYRIGHT",
            "docs/UNICODE-LICENSE.txt": "UNICODE-LICENSE.txt",
        },
    },
}

# The vendored C sources compiled into the package, every C file of these
# directories: (library, directory, wrapper name prefix, build constraint).
COMPILED = [
    ("rmrender", "src", "clib_render_", None),
    ("rmrender", "adapters", "clib_render_adapter_", None),
    ("rmrender", "backends/common", "clib_render_common_", None),
    ("rmrender", "backends/apple", "clib_render_apple_", APPLE),
    ("rmrender", "backends/linux", "clib_render_cairo_", CAIRO),
    ("rmlines", "src", "clib_lines_", None),
    ("rmdoc", "src", "clib_doc_", None),
    ("rmmarks", "src", "clib_marks_", None),
]

# Sources rmrender-lib's CMake compiles with _GNU_SOURCE: the Cairo text
# component, including the calibration it shares with the Apple backend,
# which the define leaves as it is.
GNU_SOURCE = {
    "rmrender/backends/common/rmr_font_calibration.c",
    "rmrender/backends/linux/rmr_emoji_pdf.c",
    "rmrender/backends/linux/rmr_fonts.c",
    "rmrender/backends/linux/rmr_hvar.c",
    "rmrender/backends/linux/rmr_layout.c",
    "rmrender/backends/linux/rmr_page_text.c",
}

# The rmdoc-lib files that include miniz, each by exactly one line.
MINIZ_USERS = ["src/rmd_miniz.c", "src/rmd_miniz.h"]

# Fonts go to package fonts; these suffixes are the font resources.
FONT_SUFFIXES = (".ttf", "-OFL.txt", "-SOURCE.md")

LIBRARY_PREFIXES = ("rm_", "rmd_", "rmm_", "rmr_")
PREFIX = "rmrgo_"


def fail(message):
    print(f"vendor.py: {message}", file=sys.stderr)
    sys.exit(1)


def run(arguments, cwd=None):
    result = subprocess.run(arguments, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        fail(f"{shlex.join(arguments)} failed:\n{result.stdout}{result.stderr}")
    return result.stdout


def describe(checkout, allow_dirty):
    """The tag description and full commit of a checkout, refusing local
    changes unless allowed."""
    if run(["git", "-C", str(checkout), "status", "--porcelain", "--untracked-files=no"]).strip() and not allow_dirty:
        fail(f"{checkout} has uncommitted changes")
    tag = run(["git", "-C", str(checkout), "describe", "--tags", "--always", "--dirty"]).strip()
    commit = run(["git", "-C", str(checkout), "rev-parse", "HEAD"]).strip()
    return tag, commit


def copy_tree(source, destination):
    """Regular files of source, not its subdirectories, byte for byte."""
    if not source.is_dir():
        fail(f"missing directory {source}")
    destination.mkdir(parents=True, exist_ok=True)
    copied = 0
    for entry in sorted(source.iterdir()):
        if entry.is_file() and not entry.name.startswith("."):
            shutil.copyfile(entry, destination / entry.name)
            copied += 1
    if not copied:
        fail(f"no files in {source}")


def assemble(checkouts, stage):
    """Copies every library into stage/internal/clib and answers the VERSION
    lines."""
    clib = stage / "internal" / "clib"
    lines = []
    for name, spec in LIBRARIES.items():
        checkout = checkouts[name]
        root = clib / name
        for source, destination in spec["directories"].items():
            copy_tree(checkout / source, root / destination)
        for source, destination in spec["files"].items():
            path = checkout / source
            if not path.is_file() or path.stat().st_size == 0:
                fail(f"missing or empty {path}")
            (root / destination).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, root / destination)
        tag, commit = checkouts[name + ".version"]
        lines.append(f"{spec['repository']} {tag} {commit}")

    # Point the codec includes at miniz/. Each file holds the include exactly
    # once before and none after, or rmdoc-lib has changed how it reaches the
    # codec and this script must change with it.
    for relative in MINIZ_USERS:
        path = clib / "rmdoc" / relative
        text = path.read_text()
        if text.count('"../vendor/miniz/') != 1:
            fail(f"rmdoc {relative} does not include ../vendor/miniz/ exactly once")
        path.write_text(text.replace('"../vendor/miniz/', '"../miniz/'))
    (clib / "VERSION").write_text("\n".join(lines) + "\n")
    return lines


def fonts(checkout, stage):
    """Copies the bundled fonts and their licences into stage/fonts."""
    source = checkout / "resources" / "fonts"
    destination = stage / "fonts"
    destination.mkdir(parents=True)
    copied = [f for f in sorted(source.iterdir()) if f.is_file() and f.name.endswith(FONT_SUFFIXES)]
    if not any(f.suffix == ".ttf" for f in copied):
        fail(f"no fonts in {source}")
    for f in copied:
        shutil.copyfile(f, destination / f.name)


def wrappers(stage):
    """Writes one wrapper per compiled C source and answers them as
    (wrapper name, vendored path relative to internal/clib, constraint)."""
    clib = stage / "internal" / "clib"
    result = []
    for library, directory, prefix, constraint in COMPILED:
        for source in sorted((clib / library / directory).glob("*.c")):
            relative = f"{library}/{directory}/{source.name}"
            stem = source.stem
            for strip in ("rmr_", "rmd_", "rmm_", "rm_"):
                if stem.startswith(strip):
                    stem = stem[len(strip):]
                    break
            name = f"{prefix}{stem}.c"
            text = HEADER + "\n"
            text += f"// {GENERATED}\n//\n"
            text += f"// Compiles the vendored {LIBRARIES[library]['repository']} {directory}/{source.name}\n"
            text += "// into this package: cgo builds only the C files of the package directory.\n"
            if constraint:
                text += f"\n//go:build {constraint}\n"
            text += '\n#include "clib_digest.h"\n'
            if relative in GNU_SOURCE:
                text += "#ifndef _GNU_SOURCE\n#define _GNU_SOURCE\n#endif\n"
            text += f'#include "internal/clib/{relative}"\n'
            if any(n == name for n, _, _ in result):
                fail(f"two sources would share the wrapper {name}")
            (stage / name).write_text(text)
            result.append((name, relative, constraint))
    return result


def digest(stage, version_lines):
    """Writes clib_digest.h with a digest of every file under internal/clib."""
    clib = stage / "internal" / "clib"
    h = hashlib.sha256()
    for path in sorted(p for p in clib.rglob("*") if p.is_file()):
        relative = path.relative_to(clib).as_posix()
        h.update(f"{hashlib.sha256(path.read_bytes()).hexdigest()} {relative}\n".encode())
    value = h.hexdigest()
    versions = "".join(f"//   {line}\n" for line in version_lines)
    text = HEADER + f"""
// {GENERATED}
//
// A digest of every file under internal/clib, which holds:
//
{versions}//
// Each clib_*.c includes this file, so a change to the vendored sources
// changes a file in the package directory, which is what Go's build cache
// tracks.

#ifndef RMRENDER_GO_CLIB_DIGEST_H
#define RMRENDER_GO_CLIB_DIGEST_H

#define RMRENDER_GO_CLIB_DIGEST "{value}"

#endif
"""
    (stage / "clib_digest.h").write_text(text)
    return value


def compile_flags(stage, pdfium):
    clib = stage / "internal" / "clib"
    common = ["-std=c2x", "-ffp-contract=off", "-w", "-I", str(stage)]
    for library in LIBRARIES:
        common += ["-I", str(clib / library / "include")]
        if library != "rmrender":
            common += ["-I", str(clib / library / "src")]
    apple = common + ["-I", str(clib / "rmrender" / "backends" / "apple")]
    cairo = common + ["-I", str(clib / "rmrender" / "backends" / "linux"), "-I", str(pdfium / "include")]
    cairo += shlex.split(run(["pkg-config", "--cflags"] + CAIRO_PACKAGES))
    return apple, cairo


def symbols(stage, sources, pdfium, compiler):
    """Compiles every wrapper for the backends it builds with and answers
    the external symbols the objects define."""
    apple, cairo = compile_flags(stage, pdfium)
    jobs = []
    for name, _, constraint in sources:
        if constraint in (None, APPLE):
            jobs.append((name, "apple", apple))
        if constraint in (None, CAIRO):
            jobs.append((name, "cairo", cairo))
    objects = Path(tempfile.mkdtemp(prefix="rmrender-go-symbols-"))
    try:
        def build(job):
            name, backend, flags = job
            out = objects / f"{backend}-{name}.o"
            run([compiler, *flags, "-c", str(stage / name), "-o", str(out)])
            return out

        with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
            built = list(pool.map(build, jobs))
        found = set()
        for out in built:
            for line in run(["nm", "-g", str(out)]).splitlines():
                parts = line.split()
                if len(parts) < 2 or parts[-2] in ("U", "u", "w", "v"):
                    continue
                symbol = parts[-1]
                if sys.platform == "darwin":
                    if not symbol.startswith("_"):
                        continue
                    symbol = symbol[1:]
                found.add(symbol)
    finally:
        shutil.rmtree(objects, ignore_errors=True)
    if not found:
        fail("no symbols found")
    return sorted(found)


def symbols_header(stage, names):
    odd = [n for n in names if not n.startswith(LIBRARY_PREFIXES)]
    lines = "".join(f"#define {n} {PREFIX}{n}\n" for n in names)
    text = HEADER + f"""
// {GENERATED}
//
// Renames every external symbol of the vendored C libraries to {PREFIX}<name>.
// clib_prelude.h includes this file and cgo force-includes the prelude into
// every C file of the package, the vendored sources and the cgo preambles
// alike, so that the C names stay as written and the linker sees only the
// prefixed ones: rmlines-go, rmdoc-go and rmmarks-go compile the same
// libraries under their own names, and one program may link them all.
// {len(names)} symbols, read with nm from objects of both backends; Windows
// compiles the Cairo backend's sources, and its _WIN32 branches add no other.

#ifndef RMRENDER_GO_CLIB_SYMBOLS_H
#define RMRENDER_GO_CLIB_SYMBOLS_H

{lines}
#endif
"""
    (stage / "clib_symbols.h").write_text(text)
    return odd


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for name, spec in LIBRARIES.items():
        parser.add_argument(f"--{name}", type=Path, required=True, help=f"a {spec['repository']} checkout")
    parser.add_argument("--pdfium", type=Path, required=True, help="a PDFium SDK (its include/ is read)")
    parser.add_argument("--cc", default=os.environ.get("CC", "cc"), help="the C compiler (default $CC or cc)")
    parser.add_argument("--allow-dirty", action="store_true", help="vendor checkouts with uncommitted changes")
    args = parser.parse_args()

    if sys.platform != "darwin":
        fail("reading the Apple backend's symbols needs macOS")
    module = Path(__file__).resolve().parent.parent
    checkouts = {}
    for name in LIBRARIES:
        checkout = getattr(args, name).resolve()
        if checkout == module or module in checkout.parents or checkout in module.parents:
            fail(f"{checkout} overlaps {module}")
        checkouts[name] = checkout
        checkouts[name + ".version"] = describe(checkout, args.allow_dirty)
    if not (args.pdfium / "include" / "fpdfview.h").is_file():
        fail(f"{args.pdfium} holds no include/fpdfview.h")

    stage = Path(tempfile.mkdtemp(prefix=".vendor-staging-", dir=module))
    try:
        version_lines = assemble(checkouts, stage)
        fonts(checkouts["rmrender"], stage)
        sources = wrappers(stage)
        value = digest(stage, version_lines)
        names = symbols(stage, sources, args.pdfium.resolve(), args.cc)
        odd = symbols_header(stage, names)

        # Swap in: the vendored tree, the font files, the generated files.
        clib = module / "internal" / "clib"
        retired = Path(tempfile.mkdtemp(prefix=".vendor-retired-", dir=module))
        try:
            if clib.exists():
                shutil.move(str(clib), str(retired / "clib"))
            clib.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(stage / "internal" / "clib"), str(clib))
        except BaseException:
            if (retired / "clib").exists() and not clib.exists():
                shutil.move(str(retired / "clib"), str(clib))
            raise
        shutil.rmtree(retired, ignore_errors=True)

        font_dir = module / "fonts"
        font_dir.mkdir(exist_ok=True)
        for old in font_dir.iterdir():
            if old.is_file() and old.name.endswith(FONT_SUFFIXES):
                old.unlink()
        for new in (stage / "fonts").iterdir():
            shutil.copyfile(new, font_dir / new.name)

        for old in module.glob("clib_*.c"):
            if GENERATED in old.read_text():
                old.unlink()
        for name, _, _ in sources:
            shutil.copyfile(stage / name, module / name)
        for name in ("clib_digest.h", "clib_symbols.h"):
            shutil.copyfile(stage / name, module / name)
    finally:
        shutil.rmtree(stage, ignore_errors=True)

    for line in version_lines:
        print(f"vendored {line}")
    print(f"{len(sources)} wrappers, {len(names)} symbols renamed, digest {value}")
    if odd:
        print("renamed symbols without a library prefix: " + ", ".join(odd))
    print(f"compiler: {args.cc} on {platform.platform()}")


if __name__ == "__main__":
    main()
